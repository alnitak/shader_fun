import 'dart:io';

import 'package:flutter/services.dart' show rootBundle;

import '../core/shader_types.dart';
import 'impellerc_runner_io.dart';
import 'shader_compiler_core.dart';

export 'impellerc_runner_io.dart' show findImpellercBinary;

Future<CompileResult?> _tryLoadPrebuiltBundle(String assetKey) async {
  for (final key in [assetKey, 'packages/shader_fun/$assetKey']) {
    try {
      final byteData = await rootBundle.load(key);
      final bytes = byteData.buffer.asUint8List(
        byteData.offsetInBytes,
        byteData.lengthInBytes,
      );
      return CompileResult.success(bytes);
    } catch (_) {}
  }
  return null;
}

Future<CompileResult> runImpellerCompile({
  required String quadVertexShader,
  required String wrappedFragGlsl,
  String? customImpellercPath,
  String? rawUserGlsl,
  String? rawCommonGlsl,
  Map<String, int>? customUniformSlots,
  PassType passType = PassType.image,
  ShaderPassMode mode = ShaderPassMode.shaderToy,
}) async {
  final hash = ImpellerCompilerCore.computeBundleHash(
    vertexGlsl: quadVertexShader,
    fragmentGlsl: wrappedFragGlsl,
  );
  final assetKey = ImpellerCompilerCore.bundleAssetKeyForHash(hash);

  // On mobile (iOS / Android), impellerc cannot be invoked on-device.
  // Load the pre-compiled .shaderbundle generated by hook/build.dart.
  if (Platform.isIOS || Platform.isAndroid) {
    final prebuilt = await _tryLoadPrebuiltBundle(assetKey);
    if (prebuilt != null) {
      return prebuilt;
    }
    return CompileResult.error(
      'Pre-compiled shader bundle not found ($assetKey). '
      'Ensure hook/build.dart is present and rebuild the app.',
    );
  }

  final impellerc = customImpellercPath ?? findImpellercBinary();
  if (impellerc == null) {
    final prebuilt = await _tryLoadPrebuiltBundle(assetKey);
    if (prebuilt != null) {
      return prebuilt;
    }
    return const CompileResult.error(
      'Could not locate "impellerc" compiler binary in Flutter SDK. '
      'Please ensure Flutter is installed and on PATH.',
    );
  }

  return invokeImpellercProcess(
    quadVertexShader: quadVertexShader,
    wrappedFragGlsl: wrappedFragGlsl,
    customImpellercPath: impellerc,
  );
}
